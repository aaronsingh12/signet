// Fixed, versioned detector benchmarks (DA 6 mechanism 4: "attacks, benign traffic, multilingual sets").
// A set never changes once released: a change is a new set version, so results stay comparable between
// a champion and a challenger. label 1 = what the detector must catch, 0 = traffic it must leave alone.

