test('administrator deletion erases agent data, credentials and managed copies while other agents and signed evidence remain verifiable', async () => {
  const { hashRecord, verifyChain, verifyInclusion, verifyJws, sha256 } = await import('@signet/core');
  const { permissionsFor } = await import('../src/rbac');
  const { registerAgent, issueSeal, getAgent } = await import('../src/registry');
  const { createDeploymentCredential, exchangeDeploymentCredential } = await import('../src/deployment-identity');
  const { createBootstrap } = await import('../src/identity');
  const { removeAgent, agentRemovalPreview } = await import('../src/agent-removal');
  const { db } = await import('../src/db');
  const { keys } = await import('../src/keys');
  const { tenant } = await import('../src/tenant');
  const ledger = await import('../src/ledger');
  const evidence = await import('../src/evidence');
  const owner: Principal = { id: 'owner@example.test', name: 'Owner', kind: 'human', roles: ['agent_owner'], permissions: permissionsFor(['agent_owner']), groups: [], mfa: true, auth: 'bearer', auth_time: null };
  const security: Principal = { ...owner, id: 'security@example.test', roles: ['security_officer'], permissions: permissionsFor(['security_officer']) };
  const admin: Principal = { ...owner, id: 'admin@example.test', roles: ['tenant_admin'], permissions: permissionsFor(['tenant_admin']) };
  const agents = (await Promise.all(['erase-agent', 'keep-agent'].map(async (handle) => (await registerAgent({ handle, name: handle, purpose: 'Real deletion integration', sponsor: owner.id, tier: 'T1', autonomy_level: 'L0', team: [{ user: 'builder@example.test', role: 'builder' }] }, owner)))));
  for (const agent of agents) (await issueSeal(agent.id, { models: [{ model: 'gpt-oss:120b-cloud', region: 'unverified' }], tools: [], limits: { rpm: 30, tokens_per_day: 1000, usd_per_day: 1 }, environments: ['dev'] }, security));
  const erased = agents[0]!;
  const kept = agents[1]!;
  const deployment = (await createDeploymentCredential(erased.id, owner, 'dev'));
  const identity = (await exchangeDeploymentCredential(deployment.deployment_credential));
  (await createBootstrap(erased.id, owner, 'dev'));
  const otherDeployment = (await createDeploymentCredential(kept.id, owner, 'dev'));
  const workflow = await import('../src/workflow');
  for (const agent of agents) (await workflow.start(agent, { users_affected: ['internal'] }, owner));
  const yesterday = new Date(Date.now() - 86_400_000).toISOString().slice(0, 10);
  const oldIds: string[] = [];
  for (const agent of agents) {
    const previous = [...(await ledger.all())].at(-1)!;
    const record: Omit<LedgerRecord, 'record_hash'> = { record_id: `old_${agent.id}`, seq: previous.seq + 1, tenant_id: tenant.id, kind: 'transaction', ts: `${yesterday}T10:00:00.000Z`, agent_id: agent.id, cert_id: null, data: { action_type: 'llm_call', outcome: 'success', private_value: `${agent.handle} private content` }, prev_hash: previous.record_hash };
    (await db.prepare('INSERT INTO ledger_record (seq, record_id, tenant_id, kind, ts, agent_id, cert_id, data, prev_hash, record_hash) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)').run(record.seq, record.record_id, tenant.id, record.kind, record.ts, agent.id, null, JSON.stringify(record.data), record.prev_hash, hashRecord(record)));
    oldIds.push(record.record_id);
  }
  (await ledger.append({ kind: 'admin', data: { event: 'shared.reference', agents: [erased.id, kept.id] } }));
  (await evidence.sealFinishedDays());
  const root = ((await evidence.roots(10)) as { jws: string }[])[0]!.jws;
  const otherRecord = (await ledger.get(oldIds[1]!));
  (await db.prepare('INSERT INTO idempotency_key VALUES (?, ?, ?, ?, ?, ?, ?)').run('test', owner.id, 'POST', '/api/v1/agents', 201, JSON.stringify(erased), new Date().toISOString()));
  writeFileSync(join(directory, 'hospital-agents.json'), JSON.stringify({ erased: deployment, kept: otherDeployment }));
  writeFileSync(join(directory, 'hospital-agents.env'), `ERASE=${deployment.deployment_credential}\nKEEP=${otherDeployment.deployment_credential}\n`);
  writeFileSync(join(directory, 'hospital-workload.json'), JSON.stringify(identity));
  mkdirSync(join(directory, 'exports'));
  const output = new PassThrough();
  const chunks: Buffer[] = [];
  output.on('data', (chunk: Buffer) => chunks.push(chunk));
  const completed = once(output, 'end');
  (await evidence.writePackage(output, { actor: admin.id }));
  await completed;
  const exportFile = join(directory, 'exports', 'test.sep');
  writeFileSync(exportFile, Buffer.concat(chunks));
  await assert.rejects(async () => (await agentRemovalPreview(erased.id, owner)), /administrator/);
  await assert.rejects(removeAgent(erased.id, erased.handle, { ...admin, kind: 'service' }), /administrator/);
  await assert.rejects(removeAgent(erased.id, 'wrong-handle', admin), /exact agent handle/);
  assert.equal((await getAgent(erased.id)).status, 'sealed');
  const preview = (await agentRemovalPreview(erased.id, admin));
  assert.equal(preview.certificates, 1);
  assert.equal(preview.deployments, 1);
  assert.equal(preview.credentials, 2);
  const result = await removeAgent(erased.id, erased.handle, admin);
  assert.equal(result.deleted, true);
  await assert.rejects(async () => (await getAgent(erased.id)), /not found/);
  await assert.rejects(async () => (await exchangeDeploymentCredential(deployment.deployment_credential)), /unknown or revoked/);
  assert.equal((await exchangeDeploymentCredential(otherDeployment.deployment_credential)).claims.agent_id, kept.id);
  assert.deepEqual((await ledger.get(oldIds[1]!)), otherRecord);
  await assert.rejects(async () => (await ledger.get(oldIds[0]!)), /not found/);
  for (const table of ['agent_team_member', 'certificate', 'bootstrap_credential', 'deployment_credential', 'agent_instance', 'issued_token', 'enforcement_event', 'enforcement_state', 'ledger_record', 'lifecycle', 'approval_request', 'agent_client', 'agent_diagnostic']) assert.equal(((await db.prepare(`SELECT COUNT(*) AS n FROM ${table} WHERE agent_id = ?`).get(erased.id)) as { n: number }).n, 0, table);
  assert.equal(((await db.prepare('SELECT COUNT(*) AS n FROM idempotency_key').get()) as { n: number }).n, 0);
  assert(!existsSync(join(directory, 'hospital-workload.json')));
  for (const file of [join(directory, 'hospital-agents.json'), join(directory, 'hospital-agents.env'), join(directory, 'worm', tenant.id, 'segments', `${yesterday}.jsonl`)]) assert(!readFileSync(file, 'utf8').includes(erased.id), file);
  assert(!readFileSync(join(directory, 'hospital-agents.env'), 'utf8').includes(deployment.deployment_credential));
  const exported = gunzipSync(readFileSync(exportFile)).toString('utf8');
  assert(!exported.includes(erased.id));
  assert(exported.includes(kept.id));
  assert.equal((await ledger.verify()).ok, true);
  assert((await ledger.verify()).erased_count! > 0);
  const trust = new Map([[keys.ledger.kid, keys.ledger.publicKey]]);
  const exportLines = exported.trimEnd().split('\n');
  const end = JSON.parse(exportLines.at(-1)!) as { sha256: string; signature: string };
  const digest = sha256(exportLines.slice(0, -1).join('\n') + '\n');
  assert.equal(end.sha256, digest);
  assert.equal(verifyJws<{ sha256: string }>(end.signature, trust, 'signet-sep').payload.sha256, digest);
  const exportedRecords = exportLines.slice(0, -1).map((line) => JSON.parse(line) as { type: string; record?: LedgerRecord }).filter((line) => line.type === 'record').map((line) => line.record!);
  assert.equal(verifyChain(exportedRecords, undefined, trust).ok, true);
  const rows = [...(await ledger.all())];
  assert.equal(verifyChain(rows).ok, false, 'Erasure cannot be trusted without a signing key');
  const changed = rows.map((row) => row.erasure_proof ? { ...row, data: { forged: true } } : row);
  assert.equal(verifyChain(changed, undefined, trust).ok, false);
  assert.equal(((await evidence.roots(10)) as { jws: string }[])[0]!.jws, root);
  const proof = (await evidence.proofFor(otherRecord.record_id));
  assert(verifyInclusion(proof.record_hash, proof.index, proof.tree_size, proof.proof, evidence.verifyRootJws(root).merkle_root));
  await assert.rejects(async () => (await ledger.append({ kind: 'transaction', agent_id: erased.id, data: { event: 'late_write' } })), /removed agents/);
  await assert.rejects(async () => (await db.prepare('UPDATE ledger_record SET data = ? WHERE seq = 1').run('{}')), /append-only/);
  const replacement = (await registerAgent({ handle: erased.handle, name: 'New lifecycle', purpose: 'New identity', sponsor: owner.id, tier: 'T1', autonomy_level: 'L0' }, owner));
  assert.notEqual(replacement.id, erased.id);
});

test('unprovisioned proposals can be erased with historical or disconnected gateways; runtime identities still require cleanup', async () => {
  const { db } = await import('../src/db');
  const { permissionsFor } = await import('../src/rbac');
  const { registerAgent, issueSeal, getAgent } = await import('../src/registry');
  const { removeAgent, agentRemovalPreview } = await import('../src/agent-removal');
  const ledger = await import('../src/ledger');
  const owner: Principal = { id: 'proposal-owner@example.test', name: 'Owner', kind: 'human', roles: ['agent_owner'], permissions: permissionsFor(['agent_owner']), groups: [], mfa: true, auth: 'bearer', auth_time: null };
  const admin: Principal = { ...owner, id: 'proposal-admin@example.test', roles: ['tenant_admin'], permissions: permissionsFor(['tenant_admin']) };
  const security: Principal = { ...owner, id: 'proposal-security@example.test', roles: ['security_officer'], permissions: permissionsFor(['security_officer']) };
  for (const [node, seen] of [['old-vercel-container', '2020-01-01T00:00:00.000Z'], ['disconnected-current-container', new Date().toISOString()]]) {
    await db.prepare('INSERT INTO gateway_node (id, last_seen) VALUES (?, ?)').run(node!, seen!);
  }
  const proposal = await registerAgent({ handle: 'unprovisioned-support-assistant', name: 'Customer Support Assistant', purpose: 'Proposed external assistant without runtime credentials', sponsor: owner.id, autonomy_level: 'L0' }, owner);
  await ledger.append({ kind: 'admin', agent_id: proposal.id, data: { event: 'proposal.reviewed' } });
  await ledger.append({ kind: 'admin', agent_id: proposal.id, data: { event: 'proposal.configured' } });
  const preview = await agentRemovalPreview(proposal.id, admin);
  assert.equal(preview.certificates, 0);
  assert.equal(preview.deployments, 0);
  assert.equal(preview.credentials, 0);
  assert.equal(preview.records, 3);
  await assert.rejects(removeAgent(proposal.id, 'incorrect-handle', admin), /exact agent handle/);
  assert.equal((await removeAgent(proposal.id, proposal.handle, admin)).deleted, true);
  await assert.rejects(getAgent(proposal.id), /not found/);
  assert.equal((await ledger.verify()).ok, true);
  assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM gateway_node').get())!.n, 2, 'Unrelated Gateway registrations must be preserved');

  const runtime = await registerAgent({ handle: 'provisioned-support-assistant', name: 'Provisioned assistant', purpose: 'Approved runtime identity still needs Gateway cleanup', sponsor: owner.id, autonomy_level: 'L0' }, owner);
  await issueSeal(runtime.id, { models: [{ model: 'gpt-oss:120b-cloud', region: 'unverified' }], tools: [], limits: { rpm: 30, tokens_per_day: 1000, usd_per_day: 1 }, environments: ['dev'] }, security);
  await assert.rejects(removeAgent(runtime.id, runtime.handle, admin), /Reconnect registered gateways/);
  assert.equal((await getAgent(runtime.id)).status, 'sealed', 'Refused runtime deletion must not erase or stop the agent');
});
