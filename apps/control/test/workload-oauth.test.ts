import { strict as assert } from 'node:assert';
import { createHash, randomBytes } from 'node:crypto';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, test } from 'node:test';
import express from 'express';
import { createServer } from 'node:http';
import type { Principal } from '../src/rbac';
import { dropTestDatabase } from './database';

process.env.SIGNET_DATA_DIR = mkdtempSync(join(tmpdir(), 'signet-workload-oauth-'));
process.env.MONGODB_DATABASE = 'test_' + Date.now().toString(36) + '_' + randomBytes(6).toString('hex');
process.env.SIGNET_AUTH_MODE = 'local';
process.env.SIGNET_ADMIN_ID = 'oauth-admin@example.test';
process.env.SIGNET_ADMIN_PASSWORD = randomBytes(24).toString('hex');
after(dropTestDatabase);

interface TokenResponse { access_token: string; refresh_token: string; token_type: string; expires_in: number; scope: string }

test('real HTTP authorization, local sign-in, consent, PKCE, rotating refresh and revocation use isolated MongoDB', async () => {
  const { db } = await import('../src/db');
  const { sha256, verifyJws } = await import('@signet/core');
  const { keys } = await import('../src/keys');
  const { workloadOAuthRouter } = await import('../src/workload-oauth-routes');
  const { route, problemHandler } = await import('../src/http');
  const { localLogin } = await import('../src/oidc');
  const { permissionsFor } = await import('../src/rbac');
  const { registerAgent, issueSeal } = await import('../src/registry');
  const { ensureSavedClient, createClient, revokeClient } = await import('../src/identity');
  const { beginAuthorization, authorizationPreview } = await import('../src/workload-oauth');
  const owner: Principal = { id: process.env.SIGNET_ADMIN_ID!, name: 'OAuth administrator', kind: 'human', roles: ['tenant_admin', 'security_officer', 'agent_owner'], permissions: permissionsFor(['tenant_admin', 'security_officer', 'agent_owner']), groups: [], mfa: true, auth: 'session', auth_time: null };
  const agent = await registerAgent({ handle: 'oauth-flow-agent', name: 'OAuth flow agent', purpose: 'Verify real external authorization code connections', sponsor: owner.id, tier: 'T1', autonomy_level: 'L0' }, owner);
  await issueSeal(agent.id, { models: [{ model: 'gpt-oss:120b-cloud', region: 'unverified' }], tools: [], limits: { rpm: 10, tokens_per_day: 1000, usd_per_day: 1 }, environments: ['dev'] }, { ...owner, id: 'security@example.test' });
  const client = (await ensureSavedClient(agent.id, owner, 'ServiceNow authorization code', 'dev')).credentials!;
  const app = express();
  app.use(express.json());
  app.post('/api/v1/auth/local-login', route((req, res) => localLogin(req, res)));
  app.use('/api/v1', workloadOAuthRouter());
  app.use(problemHandler);
  const server = createServer(app);
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  assert(address && typeof address === 'object');
  const origin = `http://127.0.0.1:${address.port}`;
  const callback = 'https://instance.service-now.com/oauth_redirect.do';
  const verifier = randomBytes(48).toString('base64url');
  const input = { response_type: 'code', client_id: client.client_id, redirect_uri: callback, state: 'state-with-characters+&=', code_challenge: createHash('sha256').update(verifier).digest('base64url'), code_challenge_method: 'S256', scope: 'mcp' };
  const authorizationPath = '/api/v1/identity/authorize?' + new URLSearchParams(input);
  const basic = 'Basic ' + Buffer.from(`${client.client_id}:${client.client_secret}`).toString('base64');
  const token = (body: Record<string, string>) => fetch(origin + '/api/v1/identity/token', { method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded', authorization: basic }, body: new URLSearchParams(body) });
  try {
    const login = await fetch(origin + '/api/v1/auth/local-login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: process.env.SIGNET_ADMIN_ID, password: process.env.SIGNET_ADMIN_PASSWORD, return_to: authorizationPath }) });
    assert.equal(login.status, 200);
    const cookie = login.headers.get('set-cookie')!.split(';')[0]!;
    const jsonHeaders = { cookie, 'content-type': 'application/json' };
    const settingsPath = origin + `/api/v1/identity/clients/${client.client_id}/oauth`;
    assert.equal((await fetch(settingsPath, { headers: { cookie } })).status, 200);
    assert.equal((await fetch(settingsPath, { method: 'PUT', headers: jsonHeaders, body: JSON.stringify({ redirect_uri: 'https://bad.test/#fragment' }) })).status, 400);
    assert.equal((await fetch(settingsPath, { method: 'PUT', headers: jsonHeaders, body: JSON.stringify({ redirect_uri: callback }) })).status, 200);
    const unauthenticated = await fetch(origin + authorizationPath, { redirect: 'manual' });
    assert.equal(unauthenticated.status, 302);
    assert(unauthenticated.headers.get('location')!.startsWith('/login?return_to='));
    const invalidRedirect = await fetch(origin + authorizationPath.replace(encodeURIComponent(callback), encodeURIComponent('https://attacker.test/callback')), { redirect: 'manual' });
    assert.equal(invalidRedirect.status, 400);
    assert.equal(invalidRedirect.headers.get('location'), null);
    const noPkce = await fetch(origin + '/api/v1/identity/authorize?' + new URLSearchParams({ ...input, code_challenge: '' }), { headers: { cookie }, redirect: 'manual' });
    assert.equal(noPkce.status, 400);
    await assert.rejects(() => beginAuthorization(input, { ...owner, id: 'not-owner@example.test', roles: ['agent_owner'], permissions: permissionsFor(['agent_owner']) }), /does not own/);
    const start = await fetch(origin + authorizationPath, { headers: { cookie }, redirect: 'manual' });
    assert.equal(start.status, 302);
    const request = new URL(start.headers.get('location')!, origin).searchParams.get('request')!;
    const previewPath = origin + '/api/v1/identity/authorization/' + request;
    const preview = await fetch(previewPath, { headers: { cookie } });
    assert.equal(preview.status, 200);
    await assert.rejects(() => authorizationPreview(request, { ...owner, id: 'different-user@example.test' }), /belongs to another user/);
    const csrf = await fetch(previewPath + '/approve', { method: 'POST', headers: { cookie, 'content-type': 'application/x-www-form-urlencoded' }, body: 'approve=true' });
    assert.equal(csrf.status, 415);
    const disguisedForm = await fetch(previewPath + '/approve', { method: 'POST', headers: { cookie, 'content-type': 'text/plain; charset=application/json' }, body: '{}' });
    assert.equal(disguisedForm.status, 415);
    const consent = await fetch(previewPath + '/approve', { method: 'POST', headers: jsonHeaders, body: '{}' });
    assert.equal(consent.status, 200);
    const redirect = new URL((await consent.json() as { redirect_to: string }).redirect_to);
    assert.equal(redirect.origin, new URL(callback).origin);
    assert.equal(redirect.searchParams.get('state'), input.state);
    const code = redirect.searchParams.get('code')!;
    const body = { grant_type: 'authorization_code', code, redirect_uri: callback, code_verifier: verifier };
    assert.equal((await fetch(previewPath + '/approve', { method: 'POST', headers: jsonHeaders, body: '{}' })).status, 400);
    assert.equal((await token({ ...body, code_verifier: randomBytes(48).toString('base64url') })).status, 400);
    assert.equal((await token({ ...body, redirect_uri: 'https://attacker.test/' })).status, 400);
    const second = await createClient(agent.id, owner, 'Other OAuth client', 'dev');
    const crossClient = await fetch(origin + '/api/v1/identity/token', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ ...body, client_id: second.client_id, client_secret: second.client_secret }) });
    assert.equal(crossClient.status, 400);
    const exchanged = await token(body);
    assert.equal(exchanged.status, 200);
    assert.equal(exchanged.headers.get('cache-control'), 'no-store');
    const tokens = await exchanged.json() as TokenResponse;
    assert(tokens.access_token && tokens.refresh_token && tokens.expires_in > 0);
    assert.equal(tokens.token_type, 'Bearer');
    const claims = verifyJws<{ agent_id: string }>(tokens.access_token, new Map([[keys.token.kid, keys.token.publicKey]]), 'JWT').payload;
    assert.equal(claims.agent_id, agent.id);
    assert.equal((await token(body)).status, 400);
    const stored = await db.prepare('SELECT token_hash FROM workload_oauth_refresh WHERE client_id = ?').get(client.client_id) as { token_hash: string };
    assert.equal(stored.token_hash, sha256(tokens.refresh_token));
    const renewed = await token({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token });
    assert.equal(renewed.status, 200);
    const rotated = await renewed.json() as TokenResponse;
    assert.notEqual(rotated.refresh_token, tokens.refresh_token);
    assert.equal((await token({ grant_type: 'refresh_token', refresh_token: tokens.refresh_token })).status, 400);
    const concurrentStart = await fetch(origin + authorizationPath, { headers: { cookie }, redirect: 'manual' });
    const concurrentRequest = new URL(concurrentStart.headers.get('location')!, origin).searchParams.get('request')!;
    const concurrentConsent = await fetch(origin + '/api/v1/identity/authorization/' + concurrentRequest + '/approve', { method: 'POST', headers: jsonHeaders, body: '{}' });
    const concurrentCode = new URL((await concurrentConsent.json() as { redirect_to: string }).redirect_to).searchParams.get('code')!;
    const concurrent = await Promise.all([token({ ...body, code: concurrentCode }), token({ ...body, code: concurrentCode })]);
    assert.deepEqual(concurrent.map(response => response.status).sort(), [200, 400]);
    const expiredStart = await fetch(origin + authorizationPath, { headers: { cookie }, redirect: 'manual' });
    const expiredRequest = new URL(expiredStart.headers.get('location')!, origin).searchParams.get('request')!;
    await db.prepare('UPDATE workload_oauth_request SET expires_at = ? WHERE request_hash = ?').run(Date.now() - 1, sha256(expiredRequest));
    assert.equal((await fetch(origin + '/api/v1/identity/authorization/' + expiredRequest, { headers: { cookie } })).status, 400);
    const expiredCodeStart = await fetch(origin + authorizationPath, { headers: { cookie }, redirect: 'manual' });
    const expiredCodeRequest = new URL(expiredCodeStart.headers.get('location')!, origin).searchParams.get('request')!;
    const expiredCodeConsent = await fetch(origin + '/api/v1/identity/authorization/' + expiredCodeRequest + '/approve', { method: 'POST', headers: jsonHeaders, body: '{}' });
    const expiredCode = new URL((await expiredCodeConsent.json() as { redirect_to: string }).redirect_to).searchParams.get('code')!;
    await db.prepare('UPDATE workload_oauth_code SET expires_at = ? WHERE token_hash = ?').run(Date.now() - 1, sha256(expiredCode));
    assert.equal((await token({ ...body, code: expiredCode })).status, 400);
    const deniedStart = await fetch(origin + authorizationPath, { headers: { cookie }, redirect: 'manual' });
    const deniedRequest = new URL(deniedStart.headers.get('location')!, origin).searchParams.get('request')!;
    const denied = await fetch(origin + '/api/v1/identity/authorization/' + deniedRequest + '/deny', { method: 'POST', headers: jsonHeaders, body: '{}' });
    assert.equal(new URL((await denied.json() as { redirect_to: string }).redirect_to).searchParams.get('error'), 'access_denied');
    const legacy = await fetch(origin + '/api/v1/identity/token', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ grant_type: 'client_credentials', client_id: client.client_id, client_secret: client.client_secret }) });
    assert.equal(legacy.status, 200);
    const wrongSecret = await fetch(origin + '/api/v1/identity/token', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ grant_type: 'authorization_code', client_id: client.client_id, client_secret: 'incorrect', code }) });
    assert.equal(wrongSecret.status, 401);
    assert.equal((await wrongSecret.json() as { error: string }).error, 'invalid_client');
    assert.equal((await token({ grant_type: 'password' })).status, 400);
    assert.equal((await token({})).status, 400);
    const metadata = await fetch(origin + '/api/v1/identity/oauth-metadata');
    assert.equal(metadata.status, 200);
    assert.deepEqual((await metadata.json() as { code_challenge_methods_supported: string[] }).code_challenge_methods_supported, ['S256']);
    await revokeClient(client.client_id, owner, 'Integration test revocation');
    assert.equal((await token({ grant_type: 'refresh_token', refresh_token: rotated.refresh_token })).status, 401);
  } finally {
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  }
});
