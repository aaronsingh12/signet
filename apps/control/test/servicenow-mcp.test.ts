import { strict as assert } from 'node:assert';
import { createHash } from 'node:crypto';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, test } from 'node:test';
import express from 'express';
import type { AddressInfo } from 'node:net';
import type { Principal } from '../src/rbac';
import { dropTestDatabase } from './database';

process.env.SIGNET_DATA_DIR = mkdtempSync(join(tmpdir(), 'signet-servicenow-'));
process.env.SIGNET_DB_SCHEMA = 'test_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 10);
process.env.SIGNET_PUBLIC_URL = 'https://signet.example.test';
after(dropTestDatabase);

test('ServiceNow connections keep independent settings and OAuth state, enforce PKCE ownership and expiry, and return no secrets', async () => {
  const { startServiceNowConnection, completeServiceNowConnection, serviceNowConnection, listServiceNowConnections } = await import('../src/servicenow-mcp');
  const { db } = await import('../src/db');
  const { route, problemHandler } = await import('../src/http');
  const { createServiceNowSettings, updateServiceNowSettings, serviceNowSettings, removeServiceNowConnection } = await import('../src/servicenow-mcp-settings');
  const { putSecret } = await import('../src/secrets');
  const { tenant } = await import('../src/tenant');
  const { SCHEMA_SQL } = await import('../src/schema');
  const actor: Principal = { id: 'admin@example.test', name: 'Admin', kind: 'human', roles: ['tenant_admin'], permissions: ['tenant.admin'], groups: [], mfa: true, auth: 'session', auth_time: null };
  const app = express();
  app.use(express.json());
  app.post('/settings', route(req => createServiceNowSettings(req.body, actor)));
  app.put('/settings/:id', route(req => updateServiceNowSettings(req.params.id!, req.body, actor)));
  app.get('/settings/:id', route(req => serviceNowSettings(req.params.id!)));
  app.delete('/connections/:id', route(req => removeServiceNowConnection(req.params.id!)));
  app.get('/connect/:id', route((req, res) => startServiceNowConnection(req.params.id!, res, actor)));
  app.get('/callback', route((req, res) => completeServiceNowConnection(req, res, actor)));
  app.get('/other-callback', route((req, res) => completeServiceNowConnection(req, res, { ...actor, id: 'other@example.test' })));
  app.use(problemHandler);
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  try {
    const input = { gateway_url: 'https://signet.example.test', instance_url: 'https://example.service-now.com',
      mcp_url: 'https://example.service-now.com/sncapps/mcp-server/mcp/monitoring', client_id: 'integration-test-client', client_secret: 'integration-test-secret' };
    const missingSecret = await fetch(`${base}/settings`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ ...input, client_secret: '' }) });
    assert.equal(missingSecret.status, 400);
    const saved = await fetch(`${base}/settings`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(input) });
    assert.equal(saved.status, 200);
    const savedBody = await saved.text();
    assert(!savedBody.includes(input.client_secret));
    assert(!savedBody.includes('client_secret_id'));
    const id = (JSON.parse(savedBody) as { id: string }).id;
    assert.equal((await serviceNowSettings(id))?.has_client_secret, true);
    const unchanged = await fetch(`${base}/settings/${id}`, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ ...input, client_secret: '' }) });
    assert.equal(unchanged.status, 200);
    const invalidEndpoint = await fetch(`${base}/settings/${id}`, { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ ...input, mcp_url: 'https://other.service-now.com/sncapps/mcp-server/mcp/monitoring' }) });
    assert.equal(invalidEndpoint.status, 400);
    const started = await fetch(`${base}/connect/${id}`, { redirect: 'manual' });
    assert.equal(started.status, 302);
    const authorization = new URL(started.headers.get('location')!);
    assert.equal(authorization.origin, 'https://example.service-now.com');
    assert.equal(authorization.pathname, '/oauth_auth.do');
    assert.equal(authorization.searchParams.get('redirect_uri'), 'https://signet.example.test/api/v1/plugins/servicenow/callback');
    const state = authorization.searchParams.get('state')!;
    const pending = await db.prepare('SELECT verifier FROM servicenow_mcp_oauth_state WHERE state_hash = ?').get(createHash('sha256').update(state).digest('hex')) as { verifier: string };
    assert.equal(authorization.searchParams.get('code_challenge'), createHash('sha256').update(pending.verifier).digest('base64url'));
    assert.equal(authorization.searchParams.get('code_challenge_method'), 'S256');
    assert.equal((await fetch(`${base}/other-callback?state=${state}&error=access_denied`)).status, 400);
    assert.equal((await fetch(`${base}/callback?state=${state}&error=access_denied`)).status, 401);
    assert.equal((await fetch(`${base}/callback?state=${state}&error=access_denied`)).status, 400);
    const next = await fetch(`${base}/connect/${id}`, { redirect: 'manual' });
    const expiredState = new URL(next.headers.get('location')!).searchParams.get('state')!;
    await db.prepare('UPDATE servicenow_mcp_oauth_state SET expires_at = ?').run(Date.now() - 1);
    assert.equal((await fetch(`${base}/callback?state=${expiredState}&code=unused`)).status, 400);
    const status = await serviceNowConnection(id);
    assert.equal(status.authorized, false);
    assert.equal(status.monitoring, false);
    const pendingBeforeEdit = await fetch(`${base}/connect/${id}`, { redirect: 'manual' });
    const invalidatedState = new URL(pendingBeforeEdit.headers.get('location')!).searchParams.get('state')!;
    const second = await createServiceNowSettings({ ...input, client_id: 'second-client', client_secret: 'second-test-secret' }, actor);
    assert.notEqual(second.id, id);
    const listed = await listServiceNowConnections();
    assert.equal(listed.length, 2);
    assert.equal((await serviceNowSettings(id))?.client_id, input.client_id);
    assert.equal((await serviceNowSettings(second.id))?.client_id, 'second-client');
    const secondConsent = await fetch(`${base}/connect/${second.id}`, { redirect: 'manual' });
    const secondAuthorization = new URL(secondConsent.headers.get('location')!);
    assert.equal(secondAuthorization.searchParams.get('client_id'), 'second-client');
    const secondState = secondAuthorization.searchParams.get('state')!;
    await updateServiceNowSettings(id, { ...input, client_secret: '', gateway_url: 'https://new-signet.example.test' }, actor);
    assert.equal((await fetch(`${base}/callback?state=${invalidatedState}&code=unused`)).status, 400);
    assert.equal((await fetch(`${base}/callback?state=${secondState}&error=access_denied`)).status, 401);
    assert.equal(await serviceNowSettings('not-in-this-tenant'), null);
    const tokens = await putSecret({ name: 'servicenow-delete-test-tokens', kind: 'platform', value: JSON.stringify({ access_token: 'test-access-token', refresh_token: 'test-refresh-token' }) }, actor);
    await db.prepare('UPDATE servicenow_mcp_account SET token_secret_id = ?, expires_at = ?, tools_json = ?, discovered_at = ? WHERE id = ?')
      .run(tokens.id, Date.now() + 60000, JSON.stringify([{ name: 'read-test', title: 'Read test', description: '' }]), new Date().toISOString(), second.id);
    const account = await db.prepare('SELECT client_secret_id FROM servicenow_mcp_account WHERE id = ?').get(second.id) as { client_secret_id: string };
    const consentBeforeRemoval = await fetch(`${base}/connect/${second.id}`, { redirect: 'manual' });
    const removedState = new URL(consentBeforeRemoval.headers.get('location')!).searchParams.get('state')!;
    const removed = await fetch(`${base}/connections/${second.id}`, { method: 'DELETE' });
    assert.equal(removed.status, 200);
    assert.equal(await serviceNowSettings(second.id), null);
    assert.equal(await db.prepare('SELECT id FROM secret WHERE id = ?').get(account.client_secret_id), undefined);
    assert.equal(await db.prepare('SELECT id FROM secret WHERE id = ?').get(tokens.id), undefined);
    assert.equal((await fetch(`${base}/callback?state=${removedState}&code=unused`)).status, 400);
    assert.equal((await listServiceNowConnections()).length, 1);
    assert.equal((await fetch(`${base}/connections/${second.id}`, { method: 'DELETE' })).status, 404);
    const legacyClient = await putSecret({ name: 'servicenow-legacy-delete-client', kind: 'platform', value: 'legacy-client-secret' }, actor);
    const legacyToken = await putSecret({ name: 'servicenow-legacy-delete-token', kind: 'platform', value: 'legacy-token-secret' }, actor);
    await db.prepare('INSERT INTO servicenow_mcp_settings (tenant_id, gateway_url, instance_url, mcp_url, client_id, client_secret_id, updated_by, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)')
      .run(tenant.id, input.gateway_url, input.instance_url, input.mcp_url, input.client_id, legacyClient.id, actor.id, new Date().toISOString());
    await db.prepare('INSERT INTO servicenow_mcp_connection (tenant_id, instance_url, mcp_url, client_id, secret_id, expires_at, updated_by, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)')
      .run(tenant.id, input.instance_url, input.mcp_url, input.client_id, legacyToken.id, Date.now() + 60000, actor.id, new Date().toISOString());
    await db.initialize(SCHEMA_SQL);
    const migratedId = `snm_${tenant.id}`;
    assert((await serviceNowSettings(migratedId)) !== null);
    await removeServiceNowConnection(migratedId);
    await db.initialize(SCHEMA_SQL);
    assert.equal(await serviceNowSettings(migratedId), null);
    assert.equal(await db.prepare('SELECT id FROM secret WHERE id = ?').get(legacyClient.id), undefined);
    assert.equal(await db.prepare('SELECT id FROM secret WHERE id = ?').get(legacyToken.id), undefined);
    assert.equal((await listServiceNowConnections()).length, 1);
  } finally {
    await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  }
});
