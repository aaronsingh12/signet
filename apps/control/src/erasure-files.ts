import { chmodSync, existsSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gunzipSync, gzipSync } from 'node:zlib';
import { DATA_DIR, REPO_ROOT, sha256, signJws, type LedgerRecord } from '@signet/core';
import { keys } from './keys';
import * as ledger from './ledger';
import { tenant } from './tenant';

interface DeploymentArtifact { agent_id: string; deployment_credential: string }
interface WorkloadArtifact { agent_id?: string; claims?: { agent_id: string } }
interface PackageLine { type: string; record?: LedgerRecord; format?: string }

/** Rewrite only Signet-owned evidence copies; signed roots still commit to the unchanged record hashes. */
export async function eraseEvidenceFiles(days: string[]): Promise<void> {
  const records = [...(await ledger.all())];
  for (const day of days) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) throw new TypeError(`Invalid evidence day: ${day}`);
    const file = join(DATA_DIR, 'worm', tenant.id, 'segments', `${day}.jsonl`);
    if (!existsSync(file)) continue;
    const segment = records.filter((record) => record.ts.startsWith(day)).map((record) => JSON.stringify(record)).join('\n') + '\n';
    chmodSync(file, 0o600);
    writeFileSync(file, segment);
    chmodSync(file, 0o444);
  }
  const directory = join(REPO_ROOT, 'exports');
  if (!existsSync(directory)) return;
  const bySequence = new Map(records.map((record) => [record.seq, record]));
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.sep')) continue;
    const file = join(directory, entry.name);
    const lines = gunzipSync(readFileSync(file)).toString('utf8').trim().split('\n').map((line) => JSON.parse(line) as PackageLine);
    if (lines[0]?.format !== 'signet-evidence-package/1') throw new TypeError(`Cannot erase unsupported Signet evidence package: ${file}`);
    let changed = false;
    const content = lines.filter((line) => line.type !== 'end').map((line) => {
      if (line.type !== 'record') return line;
      if (!line.record || typeof line.record.seq !== 'number' || typeof line.record.record_hash !== 'string') throw new TypeError(`Invalid evidence record in ${file}`);
      const current = bySequence.get(line.record.seq);
      if (!current?.erasure_proof || current.record_hash !== line.record.record_hash || JSON.stringify(current) === JSON.stringify(line.record)) return line;
      changed = true;
      return { ...line, record: current };
    });
    if (!changed) continue;
    const text = content.map((line) => JSON.stringify(line)).join('\n') + '\n';
    const digest = sha256(text);
    const signature = signJws({ format: 'signet-evidence-package/1', sha256: digest, record_count: content.filter((line) => line.type === 'record').length, roots: content.filter((line) => line.type === 'root').length }, keys.ledger, 'signet-sep');
    writeFileSync(file, gzipSync(`${text}${JSON.stringify({ type: 'end', sha256: digest, signature })}\n`));
  }
}

/** Remove the deployment files generated by Signet's hospital onboarding helper, preserving other agents. */
export function eraseDeploymentArtifacts(agentId: string): void {
  const collectionFile = join(DATA_DIR, 'hospital-agents.json');
  const environmentFile = join(DATA_DIR, 'hospital-agents.env');
  if (existsSync(collectionFile)) {
    const collection = JSON.parse(readFileSync(collectionFile, 'utf8')) as Record<string, DeploymentArtifact>;
    for (const artifact of Object.values(collection)) if (!artifact || typeof artifact.agent_id !== 'string' || typeof artifact.deployment_credential !== 'string') throw new TypeError('Invalid hospital deployment artifact; expected agent_id and deployment_credential');
    const removedCredentials = Object.values(collection).filter((artifact) => artifact.agent_id === agentId).map((artifact) => artifact.deployment_credential);
    const retained = Object.fromEntries(Object.entries(collection).filter(([, artifact]) => artifact.agent_id !== agentId));
    if (removedCredentials.length) {
      writeFileSync(collectionFile, JSON.stringify(retained, null, 2), { mode: 0o600 });
      if (existsSync(environmentFile)) {
        const retainedLines = readFileSync(environmentFile, 'utf8').split(/\r?\n/).filter((line) => !removedCredentials.some((credential) => line.includes(credential)));
        writeFileSync(environmentFile, retainedLines.join('\n'), { mode: 0o600 });
      }
    }
  }
  for (const name of ['hospital-deployment.json', 'hospital-workload.json']) {
    const file = join(DATA_DIR, name);
    if (!existsSync(file)) continue;
    const artifact = JSON.parse(readFileSync(file, 'utf8')) as WorkloadArtifact;
    if (!artifact || typeof artifact !== 'object') throw new TypeError(`Invalid deployment artifact: ${file}`);
    if (artifact.agent_id === agentId || artifact.claims?.agent_id === agentId) unlinkSync(file);
  }
}
